  function fill(text, vars) {
    if (!vars) return text;
    return String(text).replace(/\{(\w+)\}/g, (match, name) => (
      vars[name] == null ? match : String(vars[name])
    ));
  }

  function translate(lang, key, vars) {
    const pack = STRINGS[lang] || STRINGS['en-US'];
    const value = pack[key] != null ? pack[key] : STRINGS['en-US'][key];
    return fill(value == null ? key : value, vars);
  }

  function apply(root, lang) {
    const code = STRINGS[lang] ? lang : 'en-US';
    if (root.documentElement) {
      root.documentElement.lang = code === 'zh-CN' ? 'zh-Hans' : code;
    }
    root.querySelectorAll('[data-i18n]').forEach((el) => {
      const value = translate(code, el.getAttribute('data-i18n'));
      const attr = el.getAttribute('data-i18n-attr');
      if (attr) {
        attr.split(',').forEach((name) => {
          const trimmed = name.trim();
          if (trimmed) el.setAttribute(trimmed, value);
        });
      }
      if (el.hasAttribute('data-i18n-html')) el.innerHTML = value;
      else if (!el.hasAttribute('data-i18n-attr-only')) el.textContent = value;
    });
    root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
      el.setAttribute('placeholder', translate(code, el.getAttribute('data-i18n-placeholder')));
    });
    root.querySelectorAll('[data-i18n-aria]').forEach((el) => {
      el.setAttribute('aria-label', translate(code, el.getAttribute('data-i18n-aria')));
    });
    root.querySelectorAll('[data-i18n-title]').forEach((el) => {
      el.setAttribute('title', translate(code, el.getAttribute('data-i18n-title')));
    });
  }

  window.SignalI18n = { STRINGS, translate, apply };
